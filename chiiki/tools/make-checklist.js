/* ===========================================================
   照合チェックリストの生成
   使い方:  node chiiki/tools/make-checklist.js

   同梱データは出典資料と未照合の暫定値です。ネットワークのつながる環境で
   出典PDFを開きながら1行ずつ潰していくための作業表を書き出します。
   データを直したら流し直してください。
   =========================================================== */
"use strict";

const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "..");
const j = (f) => JSON.parse(fs.readFileSync(path.join(root, "data", f), "utf8"));
const meta = j("meta.json"), d1 = j("d1_municipalities.json"), d2 = j("d2_oaza.json"), d3 = j("d3_principles.json");

const 出典 = (n) => (meta.出典.find((s) => s.名称.indexOf(n) >= 0) || {}).url || "";
const 大字数 = (code) => d2.大字.filter((o) => o.市町村コード === code).length;
const 区域必要 = (m) => m.指定都市区分 === "条件不利地域を含む" || m.区分 === "一部条件不利地域";
const 印 = (b) => (b ? "済" : "☐");

const L = [];
L.push("# 照合チェックリスト");
L.push("");
L.push("同梱データは**出典資料と未照合の暫定値**です。この表に沿って照合し、");
L.push("`chiiki/data/*.json` を直してください。すべて済んだら `meta.json` の");
L.push("`dataStatus` を `\"verified\"` に変えると、画面と根拠テキストの警告が消えます。");
L.push("");
L.push("- この表は `node chiiki/tools/make-checklist.js` で生成しています。データを直したら流し直してください。");
L.push("- 直したあとは `node chiiki/tools/check-data.js` と `node chiiki/tools/test-judge.js` を通してください。");
L.push("");
L.push("## 参照する資料");
L.push("");
meta.出典.forEach((s) => L.push(`- ${s.名称}${s.現在日 ? `（${s.現在日}現在）` : ""}${s.url ? `  \n  ${s.url}` : ""}`));
L.push("");
L.push("---");
L.push("");
L.push("## 1. D1 市町村マスタ");
L.push("");
L.push("「過疎地域市町村等一覧」で、全部過疎／一部過疎（みなし過疎を含む）の別を確かめます。");
L.push("振興山村・離島振興対策実施地域・半島振興対策実施地域は所管が異なるため、それぞれの一覧が必要です。");
L.push("");
L.push("| 済 | コード | 市町村 | 暫定の区分 | 暫定の該当法令 | 大字収録 | 確認すること |");
L.push("|---|---|---|---|---|---|---|");
d1.市町村.filter((m) => !m.sample).forEach((m) => {
  const 要 = 区域必要(m);
  const やること = m.verified
    ? "確認済み（" + (m.メモ || "") + "）"
    : 要 ? "一部条件不利で正しいか。正しければ条件不利区域にあたる旧市町村名をすべて拾う"
         : "全部条件不利で正しいか。一部指定なら区分を一部条件不利に変え、D2に大字を足す";
  L.push(`| ${印(m.verified)} | ${m.コード} | ${m.市町村名} | ${m.区分} | ${(m.該当法令 || []).join("・") || "—"} | ${要 ? 大字数(m.コード) + " 件" : "不要"} | ${やること} |`);
});
L.push("");
L.push("動作確認用サンプル（実データではありません。判定分岐を画面で確かめるためだけに入れています）");
L.push("");
L.push("| コード | 市町村 | ねらい |");
L.push("|---|---|---|");
d1.市町村.filter((m) => m.sample).forEach((m) => L.push(`| ${m.コード} | ${m.市町村名} | ${m.メモ || ""} |`));
L.push("");
L.push("> 実データがそろったら、この4件は削除して差し支えありません。");
L.push("");
L.push("---");
L.push("");
L.push("## 2. D2 大字→区域(b/c) テーブル");
L.push("");
L.push("本来は位置参照情報の代表点をCODHの旧市町村ポリゴンに点in判定して作ります（仕様書 §4-4）。");
L.push("いまは手入力の暫定値です。**大字の網羅性そのものが未確認**である点にご注意ください。");
L.push("実際の窓口では、収録されていない大字を選べないため「該当なし」に見えてしまいます。");
L.push("");
L.push("| 済 | 市町村 | 収録数 | (b) | (c) | 要確認 | 境界跨ぎ | 確認すること |");
L.push("|---|---|---|---|---|---|---|---|");
d1.市町村.filter(区域必要).forEach((m) => {
  const a = d2.大字.filter((o) => o.市町村コード === m.コード);
  const c = (f) => a.filter(f).length;
  L.push(`| ☐ | ${m.市町村名}${m.sample ? "（サンプル）" : ""} | ${a.length} | ${c((o) => o.区域判定 === "b")} | ${c((o) => o.区域判定 === "c")} | ${c((o) => o.区域判定 === "要確認")} | ${c((o) => o.境界跨ぎ)} | 位置参照情報の全大字がそろっているか。旧市町村名の当て方が正しいか |`);
});
L.push("");
L.push("### 突合時の落とし穴（仕様書 §4-5）");
L.push("");
L.push("| # | 事象 | 例 | 対応 |");
L.push("|---|---|---|---|");
L.push("| 1 | 旧「市」が区域として現れる | 尾道市 → 因島市 | 旧市町村名の候補に市を含める |");
L.push("| 2 | 現市名と旧市名が同一 | 柳井市 → 旧柳井市 | 市町村コード＋旧市町村IDで一意化 |");
L.push("| 3 | 県をまたぐ旧市町村 | 中津川市 → 長野県山口村 | 突合キーに現在の県コードを使わない |");
L.push("| 4 | 年次で区域が変わる | R4に呉市 安浦町が追加 | 全レコードに基準日を持たせる |");
L.push("");
L.push("---");
L.push("");
L.push("## 3. D3 確認表（原則と記号）");
L.push("");
L.push("「特別交付税措置に係る地域要件確認表」の**転入地が「3大都市圏外／全部条件不利地域」の列**だけを見ます。");
L.push("記号が ○・△・× の3種以外になったら、転入地の前提が崩れているので設計から見直してください（仕様書 §2-2）。");
L.push("");
L.push("| 済 | 転出地の条件 | 暫定の記号 | 暫定の原則 |");
L.push("|---|---|---|---|");
Object.keys(d3.対応).forEach((k) => {
  const r = d3.対応[k];
  L.push(`| ${印(r.verified)} | ${k.replace("|", " ／ ").replace("指定都市_", "指定都市・")} | ${r.記号} | ${r.原則} |`);
});
L.push("");
L.push("例外ルート（仕様書 §3-2）の根拠文も、原典の言い回しに合わせてください。");
L.push("");
L.push("| 済 | 例外 |");
L.push("|---|---|");
Object.keys(d3.例外ルート).filter((k) => k[0] !== "_").forEach((k) => L.push(`| ${印(d3.例外ルート[k].verified)} | ${d3.例外ルート[k].ラベル} |`));
L.push("");
L.push("---");
L.push("");
L.push("## 4. 仕様書 §8 の未決定事項のうち、まだ残っているもの");
L.push("");
L.push("- [ ] 「地域要件確認表」の最新版の基準日");
L.push("- [ ] 3大都市圏の人口減少率11%以上の市町村リストの入手方法（判定エンジンは `人口減少率例外` フラグで受け入れる用意ができています）");
L.push("- [ ] 振興山村・離島振興対策実施地域・半島振興対策実施地域の**区域レベル**の一覧の入手方法");
L.push("- [ ] D2 のデータ規模の試算（全国の一部条件不利地域について大字を持つ場合）");
L.push("");
L.push("決まったもの");
L.push("");
L.push("- [x] 住所入力の方式 → 都道府県 → 市町村 → 大字 の3段プルダウン");
L.push("- [x] 判定結果の履歴保存 → 保存する（「履歴に残す」を押したときだけ、ブラウザ内に最大50件）");
L.push("");

fs.writeFileSync(path.join(root, "data", "照合チェックリスト.md"), L.join("\n"), "utf8");
console.log("  出力: chiiki/data/照合チェックリスト.md");
