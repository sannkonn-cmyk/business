/* ===========================================================
   データの整合性検査
   使い方:  node chiiki/tools/check-data.js

   データを差し替えたら必ず流してください。
   エラー … 判定が壊れる。直すまでビルドしないでください
   警告   … 判定は動くが、たいてい取り込み漏れです
   =========================================================== */
"use strict";

const fs = require("fs");
const path = require("path");
const root = process.env.CHIIKI_DATA_ROOT ? path.resolve(process.env.CHIIKI_DATA_ROOT) : path.resolve(__dirname, "..");
const Judge = require(path.resolve(__dirname, "..", "src", "judge.js"));
const j = (f) => JSON.parse(fs.readFileSync(path.join(root, "data", f), "utf8"));

const meta = j("meta.json"), d1 = j("d1_municipalities.json"), d2 = j("d2_oaza.json"), d3 = j("d3_principles.json");

const エラー = [], 警告 = [];
const E = (m) => エラー.push(m);
const W = (m) => 警告.push(m);
/* 同じ種類の警告が何百件も並ぶと読めなくなるので、種類ごとにまとめます */
const まとめ = new Map();
const WM = (種類, 相手) => {
  if (!まとめ.has(種類)) まとめ.set(種類, []);
  まとめ.get(種類).push(相手);
};

const 区域法令 = Judge.区域レベルの法令;                 // 過疎・山村・離島・半島
const 全法令 = 区域法令.concat(["奄美", "小笠原", "沖縄"]);
const 区域必要 = (m) => m.指定都市区分 === "条件不利地域を含む" || m.区分 === "一部条件不利地域";
const 条件不利 = (m) => m.区分 === "全部条件不利地域" || m.区分 === "一部条件不利地域";
/* 決め方は「どうやって区域を決めたか」の記録。あとから検算するために残します。
   接頭辞 … 大字名の頭に旧市町村名が付いていた
   点in   … 国土数値情報のポリゴンに代表点が入った
   手当て … 中間CSVを手で直した */
const 決め方語 = ["接頭辞", "点in", "手当て"];

const データ未投入 = d1.市町村.length === 0 && d2.大字.length === 0;

/* ---------- D1 ---------- */
const 市町村 = {};
d1.市町村.forEach((m) => {
  const 名 = m.市町村名 || "(名称なし)";
  if (!/^[0-9]{5}$/.test(m.コード || "")) E(`D1 ${名}: 市町村コード「${m.コード}」が5桁の数字ではありません`);
  if (市町村[m.コード]) E(`D1 ${名}: 市町村コード ${m.コード} が「${市町村[m.コード].市町村名}」と重複しています`);
  市町村[m.コード] = m;

  if (["都市地域", "全部条件不利地域", "一部条件不利地域", "未確定"].indexOf(m.区分) < 0) E(`D1 ${名}: 区分「${m.区分}」は想定外です`);
  if (["該当なし", "条件不利地域を含まない", "条件不利地域を含む"].indexOf(m.指定都市区分) < 0) E(`D1 ${名}: 指定都市区分「${m.指定都市区分}」は想定外です`);

  const 該当 = m.該当法令 || [];
  const 済 = m.照合済み法令 || [];
  該当.forEach((l) => { if (全法令.indexOf(l) < 0) E(`D1 ${名}: 該当法令「${l}」は想定外です`); });
  /* 照合済み法令は「どの法令の一覧を投入したか」の記録なので、
     その市町村が該当するかどうかとは別です。含まれていなくても正常です。 */
  済.forEach((l) => { if (全法令.indexOf(l) < 0) E(`D1 ${名}: 照合済み法令「${l}」は想定外です`); });

  if (m.区分 === "都市地域" && 該当.length && m.指定都市区分 !== "条件不利地域を含む") W(`D1 ${名}: 区分が都市地域なのに該当法令（${該当.join("・")}）が入っています`);
  /* 全部条件不利地域は、どの法令によるかが分からなくても判定できます（住所によらず対象外）。
     該当法令が要るのは、区域(b/c)を見る一部条件不利地域だけです。 */
  if (m.区分 === "一部条件不利地域" && !該当.length) WM("一部条件不利地域なのに該当法令が空", 名);
  /* 未確定は「一覧が足りず区分を決められない」状態なので、該当法令が空でも正常です */

  /* (c) を言うには区域レベルの法令がすべて揃っている必要があります */
  if (区域必要(m)) {
    const 欠け = Judge.未照合の法令(m);
    if (欠け.length) WM(欠け.join("・") + " の区域一覧が未収録（この市町村では (c) が「要確認」になります）", 名);
  }
});

if (!データ未投入) {
  if (!市町村[meta.転入地.市町村コード]) W(`meta: 転入地の市町村コード ${meta.転入地.市町村コード} が D1 にありません`);
  else if (市町村[meta.転入地.市町村コード].区分 !== meta.転入地.区分) E(`meta: 転入地の区分（${meta.転入地.区分}）が D1 の ${市町村[meta.転入地.市町村コード].区分} と食い違っています`);
}

/* ---------- D2 ---------- */
const id集 = {}, 市町村別 = {};
d2.大字.forEach((o) => {
  const 名 = o.大字名 || "(名称なし)";
  if (!o.id) E(`D2 ${名}: id がありません`);
  else if (id集[o.id]) E(`D2: id ${o.id} が重複しています`);
  id集[o.id] = o;

  const 親 = 市町村[o.市町村コード];
  if (!親) { E(`D2 ${名}: 市町村コード ${o.市町村コード} が D1 にありません`); return; }
  (市町村別[o.市町村コード] = 市町村別[o.市町村コード] || []).push(o);

  if (!区域必要(親)) W(`D2 ${親.市町村名} ${名}: この市町村は区域判定に入らないため、大字を持っても使われません`);
  if (["b", "c", "要確認"].indexOf(o.区域判定) < 0) E(`D2 ${親.市町村名} ${名}: 区域判定「${o.区域判定}」は想定外です（b / c / 要確認）`);

  (o.決め方 || "").split("|").filter(Boolean).forEach((x) => {
    const 語 = x.split(":").pop();
    if (決め方語.indexOf(語) < 0) E(`D2 ${親.市町村名} ${名}: 決め方「${x}」は想定外です（${決め方語.join(" / ")}）`);
  });
  if (!o.要確認理由 && o.区域判定 !== "要確認" && !o.決め方) W(`D2 ${親.市町村名} ${名}: 決め方が記録されていません。あとから判定の妥当性を検算できません`);
  if (o.区域判定 === "要確認" && !o.要確認理由) W(`D2 ${親.市町村名} ${名}: 区域判定が要確認なのに理由が空です。画面に理由が出ません`);

  const 法令 = o.該当法令 || [];
  if (o.区域判定 === "b") {
    if (!o.旧市町村名) W(`D2 ${親.市町村名} ${名}: 区域(b) なのに該当旧市町村名が空です`);
    if (!法令.length) W(`D2 ${親.市町村名} ${名}: 区域(b) なのに該当法令が空です`);
    法令.forEach((l) => {
      if (区域法令.indexOf(l) < 0) E(`D2 ${親.市町村名} ${名}: 区域(b) の法令に「${l}」があります。区域レベルの判定に使えるのは${区域法令.join("・")}の4法令だけです（仕様書 §3-3）`);
      if ((親.該当法令 || []).indexOf(l) < 0) W(`D2 ${親.市町村名} ${名}: 区域の法令「${l}」が市町村側の該当法令に入っていません`);
      if ((親.照合済み法令 || []).indexOf(l) < 0) W(`D2 ${親.市町村名} ${名}: 区域の法令「${l}」が市町村側の照合済み法令に入っていません`);
    });
  }
  if (o.区域判定 === "c" && 法令.length) W(`D2 ${親.市町村名} ${名}: 区域(c) なのに該当法令（${法令.join("・")}）が入っています`);
});

d1.市町村.filter(区域必要).forEach((m) => {
  const 件 = (市町村別[m.コード] || []).length;
  /* 大字が無くても判定エンジンは「要確認」を返すので、判定は壊れません。
     どの市町村の区域データが足りないかを知らせる警告にとどめます。 */
  if (件 === 0) WM("区域判定が必要だが D2 に大字がない（「要確認」になります）", m.市町村名);
  else if (!(市町村別[m.コード] || []).some((o) => o.区域判定 === "b")) WM("一部条件不利地域なのに区域(b) の大字が1件もない", m.市町村名);
});

/* ---------- D3 ---------- */
["圏内", "圏外"].forEach((圏) => {
  ["都市地域", "全部条件不利地域", "一部条件不利地域", "指定都市_含まない", "指定都市_含む"].forEach((区) => {
    const k = 圏 + "|" + 区;
    const r = d3.対応[k];
    if (!r) { E(`D3: 「${k}」の行がありません`); return; }
    if (["○", "△", "×"].indexOf(r.記号) < 0) E(`D3 ${k}: 記号「${r.記号}」は想定外です。転入地が(a)固定のため ○・△・× しか出ません（仕様書 §2-2）`);
    if (r.記号 === "△" && (!r.説明b || !r.説明c)) W(`D3 ${k}: 記号が△なので、説明b と説明c の両方があると根拠テキストの文意が合います`);
    /* 対象外(×)の組合せには、確認表が原則の番号を与えていません（空で正常です） */
    if (!r.原則 && r.記号 !== "×") W(`D3 ${k}: 原則が空です`);
  });
});
Object.keys(d3.例外ルート).filter((k) => k[0] !== "_").forEach((k) => {
  if (!d3.例外ルート[k].ラベル) E(`D3 例外ルート ${k}: ラベルがありません`);
  if (!d3.例外ルート[k].根拠文) E(`D3 例外ルート ${k}: 根拠文がありません`);
});

/* ---------- 出力 ---------- */
const 数 = (f) => d2.大字.filter(f).length;
console.log("");
if (データ未投入) {
  console.log("  データはまだ投入されていません。");
  console.log("  chiiki/data/source/README.md に従って原典を置き、");
  console.log("  node chiiki/tools/ingest/build-data.js を流してください。");
  console.log("");
} else {
  console.log(`  D1 市町村   : ${d1.市町村.length} 件`);
  console.log(`  D2 大字     : ${d2.大字.length} 件（b:${数(o=>o.区域判定==="b")} / c:${数(o=>o.区域判定==="c")} / 要確認:${数(o=>o.区域判定==="要確認"||o.要確認理由)}）`);
  console.log(`  データ状態  : ${meta.dataStatus}（基準日 ${meta.基準日 || "未設定"}）`);
  console.log("");
}
エラー.forEach((m) => console.log("  エラー  " + m));
警告.forEach((m) => console.log("  警告    " + m));
[...まとめ.entries()].sort((a, b) => b[1].length - a[1].length).forEach(([種類, 相手]) => {
  console.log(`  警告    ${種類}: ${相手.length} 件`);
  console.log(`          ${相手.slice(0, 6).join("、")}${相手.length > 6 ? ` …ほか ${相手.length - 6} 件` : ""}`);
});
const まとめ件数 = [...まとめ.values()].reduce((a, b) => a + b.length, 0);
const 警告合計 = 警告.length + まとめ件数;
if (エラー.length || 警告合計) console.log("");
console.log(エラー.length === 0 ? `  検査結果: 異常なし（警告 ${警告合計} 件 / ${警告.length + まとめ.size} 種類）\n` : `  検査結果: エラー ${エラー.length} 件 / 警告 ${警告合計} 件\n`);
process.exit(エラー.length === 0 ? 0 : 1);
