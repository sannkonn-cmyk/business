/* ===========================================================
   データの整合性検査
   使い方:  node chiiki/tools/check-data.js

   データを差し替えたら必ず流してください。
   エラー … 判定が壊れる。直すまでビルドしないでください
   警告   … 判定は動くが、たいてい入力漏れです
   =========================================================== */
"use strict";

const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "..");
const j = (f) => JSON.parse(fs.readFileSync(path.join(root, "data", f), "utf8"));

const meta = j("meta.json"), d1 = j("d1_municipalities.json"), d2 = j("d2_oaza.json"), d3 = j("d3_principles.json");

const エラー = [], 警告 = [];
const E = (m) => エラー.push(m);
const W = (m) => 警告.push(m);

const 区域必要 = (m) => m.指定都市区分 === "条件不利地域を含む" || m.区分 === "一部条件不利地域";
const 条件不利 = (m) => m.区分 === "全部条件不利地域" || m.区分 === "一部条件不利地域";

/* ---------- D1 ---------- */
const 市町村 = {};
d1.市町村.forEach((m) => {
  const 名 = m.市町村名 || "(名称なし)";
  if (!/^[0-9]{5}$/.test(m.コード || "")) E(`D1 ${名}: 市町村コード「${m.コード}」が5桁の数字ではありません`);
  if (市町村[m.コード]) E(`D1 ${名}: 市町村コード ${m.コード} が「${市町村[m.コード].市町村名}」と重複しています`);
  市町村[m.コード] = m;

  if (["都市地域", "全部条件不利地域", "一部条件不利地域"].indexOf(m.区分) < 0) E(`D1 ${名}: 区分「${m.区分}」は想定外です`);
  if (["該当なし", "条件不利地域を含まない", "条件不利地域を含む"].indexOf(m.指定都市区分) < 0) E(`D1 ${名}: 指定都市区分「${m.指定都市区分}」は想定外です`);

  const 法令 = m.該当法令 || [];
  if (m.区分 === "都市地域" && 法令.length) W(`D1 ${名}: 区分が都市地域なのに該当法令（${法令.join("・")}）が入っています`);
  if (条件不利(m) && !法令.length) W(`D1 ${名}: 区分が${m.区分}なのに該当法令が空です`);
  if (m.指定都市区分 === "条件不利地域を含まない" && 法令.length) W(`D1 ${名}: 指定都市（条件不利地域を含まない）なのに該当法令が入っています`);
});

if (!市町村[meta.転入地.市町村コード]) E(`meta: 転入地の市町村コード ${meta.転入地.市町村コード} が D1 にありません`);
else if (市町村[meta.転入地.市町村コード].区分 !== meta.転入地.区分) E(`meta: 転入地の区分（${meta.転入地.区分}）が D1 の ${市町村[meta.転入地.市町村コード].区分} と食い違っています`);

/* ---------- D2 ---------- */
const id集 = {}, 市町村別 = {};
d2.大字.forEach((o) => {
  const 名 = o.大字名 || "(名称なし)";
  if (!o.id) E(`D2 ${名}: id がありません`);
  else if (id集[o.id]) E(`D2: id ${o.id} が重複しています`);
  id集[o.id] = o;

  const 親 = 市町村[o.市町村コード];
  if (!親) { E(`D2 ${名}: 市町村コード ${o.市町村コード} が D1 にありません`); return; }
  (市町村別[o.市町村コード] = 市町村別[o.市町村コード] || []).push(o);

  if (!区域必要(親)) W(`D2 ${親.市町村名} ${名}: この市町村は区域判定に入らないため、大字を持っても使われません`);
  if (["b", "c", "要確認"].indexOf(o.区域判定) < 0) E(`D2 ${親.市町村名} ${名}: 区域判定「${o.区域判定}」は想定外です（b / c / 要確認）`);

  const 法令 = o.該当法令 || [];
  if (o.区域判定 === "b") {
    if (!o.旧市町村名) W(`D2 ${親.市町村名} ${名}: 区域(b) なのに該当旧市町村名が空です`);
    if (!法令.length) W(`D2 ${親.市町村名} ${名}: 区域(b) なのに該当法令が空です`);
    法令.forEach((l) => {
      if (["過疎", "山村", "離島", "半島"].indexOf(l) < 0) E(`D2 ${親.市町村名} ${名}: 区域(b) の法令に「${l}」があります。区域レベルの判定に使えるのは過疎・山村・離島・半島の4法令だけです（仕様書 §3-3）`);
      if ((親.該当法令 || []).indexOf(l) < 0) W(`D2 ${親.市町村名} ${名}: 区域の法令「${l}」が市町村側の該当法令に入っていません`);
    });
  }
  if (o.区域判定 === "c" && 法令.length) W(`D2 ${親.市町村名} ${名}: 区域(c) なのに該当法令（${法令.join("・")}）が入っています`);
});

d1.市町村.filter(区域必要).forEach((m) => {
  const 件 = (市町村別[m.コード] || []).length;
  if (件 === 0) E(`D1 ${m.市町村名}: 区域判定が必要な区分ですが、D2 に大字が1件も収録されていません`);
  else if (!(市町村別[m.コード] || []).some((o) => o.区域判定 === "b")) W(`D1 ${m.市町村名}: 一部条件不利地域なのに、区域(b) の大字が1件もありません`);
});

/* ---------- D3 ---------- */
["圏内", "圏外"].forEach((圏) => {
  ["都市地域", "全部条件不利地域", "一部条件不利地域", "指定都市_含まない", "指定都市_含む"].forEach((区) => {
    const k = 圏 + "|" + 区;
    const r = d3.対応[k];
    if (!r) { E(`D3: 「${k}」の行がありません`); return; }
    if (["○", "△", "×"].indexOf(r.記号) < 0) E(`D3 ${k}: 記号「${r.記号}」は想定外です。転入地が(a)固定のため ○・△・× しか出ません（仕様書 §2-2）`);
    if (r.記号 === "△" && (!r.説明b || !r.説明c)) W(`D3 ${k}: 記号が△なので、説明b と説明c の両方があると根拠テキストの文意が合います`);
    if (!r.原則) W(`D3 ${k}: 原則が空です`);
  });
});
Object.keys(d3.例外ルート).filter((k) => k[0] !== "_").forEach((k) => {
  if (!d3.例外ルート[k].ラベル) E(`D3 例外ルート ${k}: ラベルがありません`);
  if (!d3.例外ルート[k].根拠文) E(`D3 例外ルート ${k}: 根拠文がありません`);
});

/* ---------- 未照合の集計 ---------- */
const 未照合市町村 = d1.市町村.filter((m) => m.verified === false && !m.sample).length;
const サンプル = d1.市町村.filter((m) => m.sample).length;
const 未照合原則 = Object.keys(d3.対応).filter((k) => d3.対応[k].verified !== true).length;

/* ---------- 出力 ---------- */
console.log("");
console.log(`  D1 市町村   : ${d1.市町村.length} 件（うち動作確認用サンプル ${サンプル} 件）`);
console.log(`  D2 大字     : ${d2.大字.length} 件（b:${d2.大字.filter(o=>o.区域判定==="b").length} / c:${d2.大字.filter(o=>o.区域判定==="c").length} / 要確認:${d2.大字.filter(o=>o.区域判定==="要確認").length} / 境界跨ぎ:${d2.大字.filter(o=>o.境界跨ぎ).length}）`);
console.log(`  D3 確認表   : ${Object.keys(d3.対応).length} 通り`);
console.log(`  データ状態  : ${meta.dataStatus}（基準日 ${meta.基準日}）`);
console.log("");
エラー.forEach((m) => console.log("  エラー  " + m));
警告.forEach((m) => console.log("  警告    " + m));
if (エラー.length || 警告.length) console.log("");

if (meta.dataStatus !== "verified") {
  console.log(`  ※ 未照合の市町村 ${未照合市町村} 件、未照合の原則 ${未照合原則} 通り。`);
  console.log("     chiiki/data/照合チェックリスト.md に従って出典資料と照合してください。");
  console.log("");
}
console.log(エラー.length === 0 ? `  検査結果: 異常なし（警告 ${警告.length} 件）\n` : `  検査結果: エラー ${エラー.length} 件 / 警告 ${警告.length} 件\n`);
process.exit(エラー.length === 0 ? 0 : 1);
