/* ===========================================================
   取り込みツールの単体テスト
   使い方:  node chiiki/tools/test-ingest.js

   合成データで、実際に起きる合併のパターンを再現して確かめます。
   実在の市町村は使いません（判定エンジンのテストと同じ理由です）。
   =========================================================== */
"use strict";

const path = require("path");
const M = require(path.join(__dirname, "ingest", "match-oaza.js"));
const R = require(path.join(__dirname, "ingest", "read-isj.js"));

let 通過 = 0, 失敗 = 0;
const 真 = (名, 条件, 補足) => {
  if (条件) { 通過++; console.log("  ok   " + 名); }
  else { 失敗++; console.log("  NG   " + 名 + (補足 ? "：" + 補足 : "")); }
};

console.log("\n[名称の整合 —— 合併で大字名の頭に旧市町村名が付くパターン]");
真("名称がそのまま",                 M.名称が整合するか("殿町", "松江村", "殿町"));
真("旧村名＋町 が頭に付く",           M.名称が整合するか("八雲町日吉", "八雲村", "日吉"));
真("旧町名がそのまま頭に付く",         M.名称が整合するか("佐田町反邊", "佐田町", "反邊"));
真("「大字」の有無を無視する",         M.名称が整合するか("多田", "湯来町", "大字多田"));
真("全角半角の違いを無視する",         M.名称が整合するか("旭ケ丘１丁目", "甲村", "旭ケ丘1丁目"));
真("無関係な名前は整合しない",        !M.名称が整合するか("新開町", "八雲村", "日吉"));
真("頭が違えば整合しない",            !M.名称が整合するか("宍道町宍道", "八雲村", "宍道"));

console.log("\n[距離]");
真("同じ点なら0m", M.距離m({ 緯度: 35.4, 経度: 133.05 }, { 緯度: 35.4, 経度: 133.05 }) === 0);
{
  const d = M.距離m({ 緯度: 35.4, 経度: 133.0 }, { 緯度: 35.41, 経度: 133.0 });
  真("緯度0.01度はおよそ1.1km", d > 1050 && d < 1160, d + "m");
}

console.log("\n[新旧の突合]");
const 旧 = [
  { 市町村コード: "32201", 市町村名: "松江市", 大字コード: "", 大字名: "殿町", 緯度: 35.470, 経度: 133.050 },
  { 市町村コード: "32341", 市町村名: "八雲村", 大字コード: "", 大字名: "日吉", 緯度: 35.400, 経度: 133.050 },
  { 市町村コード: "32304", 市町村名: "宍道町", 大字コード: "", 大字名: "宍道", 緯度: 35.410, 経度: 132.950 }
];
const 新 = [
  { 市町村コード: "32201", 市町村名: "松江市", 大字コード: "01", 大字名: "殿町",       緯度: 35.470,  経度: 133.050 },
  { 市町村コード: "32201", 市町村名: "松江市", 大字コード: "02", 大字名: "八雲町日吉", 緯度: 35.400,  経度: 133.050 },
  { 市町村コード: "32201", 市町村名: "松江市", 大字コード: "03", 大字名: "宍道町宍道", 緯度: 35.410,  経度: 132.950 },
  { 市町村コード: "32201", 市町村名: "松江市", 大字コード: "04", 大字名: "新開町",     緯度: 35.4005, 経度: 133.0505 },
  { 市町村コード: "32201", 市町村名: "松江市", 大字コード: "05", 大字名: "境目町",     緯度: 35.405,  経度: 133.000 },
  { 市町村コード: "32201", 市町村名: "松江市", 大字コード: "06", 大字名: "遠方町",     緯度: 36.500,  経度: 134.500 },
  { 市町村コード: "32201", 市町村名: "松江市", 大字コード: "07", 大字名: "座標なし町", 緯度: null,    経度: null }
];
const 結果 = M.match(新, 旧);
const 引 = (c) => 結果.find((r) => r.大字町丁目コード === c);

真("名称がそのままの大字 → 同名一致",
   引("01").突合方法 === "同名一致" && 引("01").旧市町村名 === "松江市" && !引("01").要確認理由);
真("合併で頭に村名が付いた大字 → 旧八雲村に当たる",
   引("02").突合方法 === "同名一致" && 引("02").旧市町村名 === "八雲村" && !引("02").要確認理由,
   JSON.stringify(引("02")));
真("合併で頭に町名が付いた大字 → 旧宍道町に当たる",
   引("03").旧市町村名 === "宍道町" && !引("03").要確認理由);
真("名称は違うが近いだけの大字 → 最近傍で決まる",
   引("04").突合方法 === "最近傍" && 引("04").旧市町村名 === "八雲村" && !引("04").要確認理由,
   JSON.stringify(引("04")));
真("旧市町村の境あたりの大字 → 要確認",
   !!引("05").要確認理由 && 引("05").要確認理由.indexOf("絞れません") >= 0,
   JSON.stringify(引("05")));
真("境の要確認では旧市町村を決め打ちしない", 引("05").旧市町村名 === "");
真("旧年度版にない遠方の大字 → 要確認",
   !!引("06").要確認理由 && 引("06").要確認理由.indexOf("見つかりません") >= 0,
   引("06").要確認理由);
真("座標のない大字 → 要確認",
   !!引("07").要確認理由 && 引("07").要確認理由.indexOf("座標") >= 0);
真("要確認の行には突合距離を入れない", 引("05").突合距離m === "" && 引("06").突合距離m === "");

console.log("\n[CSVの読み書き]");
{
  const csv = M.CSVにする(結果);
  const 行 = R.CSVを分ける(csv);
  真("見出しを含めて8行＋1行になる", 行.length === 結果.length + 1, 行.length + " 行");
  真("見出しの並びが仕様どおり", 行[0].join(",") === "大字町丁目コード,市町村コード,市町村名,大字名,旧市町村コード,旧市町村名,突合方法,突合距離m,要確認理由");
  const 危険 = M.CSVにする([{ 大字町丁目コード: "x", 市町村コード: "", 市町村名: "", 大字名: 'a,b"c', 旧市町村コード: "", 旧市町村名: "", 突合方法: "", 突合距離m: "", 要確認理由: "改行\nあり" }]);
  真("カンマ・引用符・改行を含む値が守られる", 危険.indexOf('"a,b""c"') >= 0 && 危険.indexOf('"改行\nあり"') >= 0, 危険);
  真("守った値を読み戻せる", (function () {
    const r = R.CSVを分ける(危険)[1];
    return r[3] === 'a,b"c' && r[8] === "改行\nあり";
  })());
  const 読み戻し = 行.slice(1).find((r) => r[0] === "05");
  真("引用符つきの値を読み戻せる", 読み戻し[8].indexOf("絞れません") >= 0, JSON.stringify(読み戻し[8]));
}
{
  const sjis = Buffer.from([0x22, 0x93, 0x87, 0x8d, 0xaa, 0x8c, 0xa7, 0x22]); // "島根県"
  真("Shift_JIS を読める", R.復号(sjis) === '"島根県"');
  真("UTF-8 も読める", R.復号(Buffer.from('"島根県"', "utf8")) === '"島根県"');
  真("BOM付きUTF-8も読める", R.復号(Buffer.from("﻿島根県", "utf8")) === "島根県");
}

console.log("\n" + (失敗 === 0 ? "すべて通過" : "失敗あり") + "：通過 " + 通過 + " / 失敗 " + 失敗 + "\n");
process.exit(失敗 === 0 ? 0 : 1);
